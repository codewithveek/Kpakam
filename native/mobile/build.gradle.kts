/** The shared contract lives two folders up, in the monorepo. Override with -PcontractDir=... */
val contractDir: File = (findProperty("contractDir") as String?)
    ?.let { file(it) }
    ?: rootDir.resolve("../../packages/contract").canonicalFile
extra["contractDir"] = contractDir

subprojects {
    apply(plugin = "org.jlleitschuh.gradle.ktlint")
    apply(plugin = "io.gitlab.arturbosch.detekt")

    extensions.configure<org.jlleitschuh.gradle.ktlint.KtlintExtension> {
        android.set(project.name == "app")
        ignoreFailures.set(false)
        filter {
            exclude { it.file.path.contains("/build/") }
        }
    }

    extensions.configure<io.gitlab.arturbosch.detekt.extensions.DetektExtension> {
        buildUponDefaultConfig = true
        allRules = false
        config.setFrom(rootProject.file("config/detekt/detekt.yml"))
        source.setFrom("src/main/kotlin", "src/test/kotlin")
    }
}
